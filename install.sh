#!/usr/bin/env bash
# moefast — install the launcher (no llama.cpp patches, no build)
#
#   ./moefast/install.sh
#
# Checks: python >= 3.10, gguf-py, llama-server. Installs ./moefast in the repo root.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$ROOT"

say() { printf '\033[1;36m[moefast]\033[0m %s\n' "$*"; }
die() { printf '\033[1;31m[moefast] %s\033[0m\n' "$*" >&2; exit 1; }

TOOL="$ROOT/tools/moefast.py"
[ -f "$TOOL" ] || die "missing $TOOL (incomplete checkout?)"

# --- python -----------------------------------------------------------------
command -v python3 >/dev/null || die "python3 not found (need >= 3.10)"
pv="$(python3 -c 'import sys;print("%d.%d"%sys.version_info[:2])')"
python3 - <<'PY' || die "python3 >= 3.10 required (found $pv)"
import sys
raise SystemExit(0 if sys.version_info >= (3, 10) else 1)
PY
say "python3 $pv"

# --- gguf-py ----------------------------------------------------------------
GGUF_PY="${MOEFAST_GGUF_PY:-}"
if [ -z "$GGUF_PY" ]; then
  for c in "$ROOT/../gguf-py" "$ROOT/gguf-py" /usr/local/lib/gguf-py; do
    [ -d "$c/gguf" ] && { GGUF_PY="$(cd "$c" && pwd)"; break; }
  done
fi
if [ -z "$GGUF_PY" ]; then
  say "WARNING: gguf-py not found — set MOEFAST_GGUF_PY=/path/to/llama.cpp/gguf-py"
else
  say "gguf-py: $GGUF_PY"
fi

# --- llama-server -----------------------------------------------------------
SERVER="${MOEFAST_LLAMA_SERVER:-$(command -v llama-server || true)}"
if [ -n "$SERVER" ]; then
  say "llama-server: $SERVER"
else
  say "WARNING: llama-server not found in PATH."
  say "         build stock llama.cpp first:  cmake -B build -DGGML_CUDA=ON && cmake --build build -j"
  say "         then either add build/bin to PATH or pass --server /path/to/llama-server"
fi

# --- wrapper ----------------------------------------------------------------
mkdir -p "$ROOT/bin"
cat > "$ROOT/bin/moefast" <<EOF
#!/bin/sh
# generated by moefast/install.sh — do not edit
MOEFAST_GGUF_PY="\${MOEFAST_GGUF_PY:-$GGUF_PY}"
export MOEFAST_GGUF_PY
exec python3 "$TOOL" "\$@"
EOF
chmod +x "$ROOT/bin/moefast"
say "installed: $ROOT/bin/moefast"

"$ROOT/bin/moefast" --help >/dev/null 2>&1 || die "smoke test failed: run ./bin/moefast --help"

say "done."
say "  next: ./bin/moefast run /path/to/model.gguf"
